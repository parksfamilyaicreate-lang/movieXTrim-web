const DEFAULT_LANG = "ja";
const LANG_STORAGE_KEY = "movieXTrim.lang";

function currentLang() {
  return I18N[activeLang] ? activeLang : DEFAULT_LANG;
}

let activeLang = (() => {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY) || DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
})();
if (!I18N[activeLang]) activeLang = DEFAULT_LANG;

function t(key, vars = {}) {
  let text = I18N[currentLang()][key];
  if (text == null) text = I18N[DEFAULT_LANG][key];
  if (text == null) return key;
  for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

function i18nVars(el) {
  try {
    return JSON.parse(el.dataset.i18nVars || "{}");
  } catch {
    return {};
  }
}

function applyTranslations() {
  document.documentElement.lang = currentLang();
  const titleEl = document.querySelector("[data-i18n-title]");
  if (titleEl) document.title = t(titleEl.dataset.i18nTitle);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n, i18nVars(el));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml, i18nVars(el));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder, i18nVars(el));
  });
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.langBtn === currentLang());
    btn.setAttribute("aria-pressed", String(btn.dataset.langBtn === currentLang()));
  });
}

function setLang(lang) {
  if (!I18N[lang]) return;
  activeLang = lang;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    /* localStorage 사용 불가 시에도 이번 세션에서는 적용 */
  }
  applyTranslations();
  document.dispatchEvent(new CustomEvent("mxt:langchange", { detail: { lang } }));
}

document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
  btn.addEventListener("click", () => setLang(btn.dataset.langBtn));
});

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", applyTranslations);
} else {
  applyTranslations();
}
